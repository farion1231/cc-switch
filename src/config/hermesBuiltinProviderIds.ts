/** Whether Hermes would route a provider key to its built-in provider. */
export function isHermesBuiltinProviderId(providerKey: string): boolean {
  return HERMES_BUILTIN_PROVIDER_IDS.has(
    providerKey.trim().toLowerCase().replace(/ /g, "-"),
  );
}
