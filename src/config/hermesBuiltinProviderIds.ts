/**
 * Hermes built-in provider ids that shadow a same-named custom provider.
 *
 * Hermes resolves `model.provider` to its built-in provider whenever the name
 * IS a canonical built-in id (`hermes_cli/runtime_provider_custom.py`,
 * `_shadowed_by_builtin`: `auth.resolve_provider(name) == name`). A CC Switch
 * card whose provider key is one of these ids is then ignored: Hermes asks for
 * the built-in's own credential (e.g. `MINIMAX_API_KEY`) and never uses the
 * card's base URL or API key. Names that are merely aliases (`kimi` →
 * `kimi-coding`, `minimax_cn` → `minimax-cn`) and explicit `custom:<name>`
 * keys still reach the custom provider.
 *
 * Generated by running `_shadowed_by_builtin` over every `PROVIDER_REGISTRY`
 * key and alias (plugin providers included) on hermes-agent rc.3-v0.22.0
 * (commit d97007c32d6, 2026-10-13). Hermes up to v2026.5.16 also shadowed
 * aliases; those versions are not covered here.
 */
