import * as React from "react";

const REDUCED_MOTION_QUERY = "(prefers-reduced-motion: reduce)";
const ANIMATION_FALLBACK_BUFFER_MS = 50;

export const OVERLAY_MOTION_CLASS =
  "data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2";

function usePrefersReducedMotion(override?: boolean): boolean {
  const [systemPreference, setSystemPreference] = React.useState(() =>
    typeof window === "undefined"
      ? false
      : (window.matchMedia?.(REDUCED_MOTION_QUERY).matches ?? false),
  );

  React.useEffect(() => {
    if (override !== undefined || !window.matchMedia) return;
    const media = window.matchMedia(REDUCED_MOTION_QUERY);
    const update = () => setSystemPreference(media.matches);
    update();
    media.addEventListener?.("change", update);
    return () => media.removeEventListener?.("change", update);
  }, [override]);

  return override ?? systemPreference;
}

function timeToMs(value: string): number {
  const trimmed = value.trim();
  if (trimmed.endsWith("ms")) return Number.parseFloat(trimmed) || 0;
  if (trimmed.endsWith("s")) return (Number.parseFloat(trimmed) || 0) * 1000;
  return 0;
}

function getAnimationTotalMs(element: HTMLElement): number {
  const style = window.getComputedStyle(element);
  const durations = style.animationDuration.split(",").map(timeToMs);
  const delays = style.animationDelay.split(",").map(timeToMs);
  const count = Math.max(durations.length, delays.length);
  let longest = 0;

  for (let index = 0; index < count; index += 1) {
    const duration = durations[index % durations.length] ?? 0;
    const delay = delays[index % delays.length] ?? 0;
    longest = Math.max(longest, duration + delay);
  }

  return longest;
}

function requestFrame(callback: FrameRequestCallback): number {
  if (window.requestAnimationFrame)
    return window.requestAnimationFrame(callback);
  return window.setTimeout(() => callback(performance.now()), 16);
}

function cancelFrame(id: number): void {
  if (window.cancelAnimationFrame) window.cancelAnimationFrame(id);
  else window.clearTimeout(id);
}

export interface OverlayAnimationGuard {
  contentRef: React.MutableRefObject<HTMLElement | null>;
  reducedMotion: boolean;
  isTransitioning: () => boolean;
  beginTransition: () => void;
  endTransition: () => void;
}

export function useOverlayAnimationGuard(
  reducedMotionOverride?: boolean,
): OverlayAnimationGuard {
  const reducedMotion = usePrefersReducedMotion(reducedMotionOverride);
  const contentRef = React.useRef<HTMLElement | null>(null);
  const transitioningRef = React.useRef(false);
  const fallbackTimerRef = React.useRef<number>();
  const frameRef = React.useRef<number>();

  const endTransition = React.useCallback(() => {
    transitioningRef.current = false;
    if (fallbackTimerRef.current !== undefined) {
      window.clearTimeout(fallbackTimerRef.current);
      fallbackTimerRef.current = undefined;
    }
    if (frameRef.current !== undefined) {
      cancelFrame(frameRef.current);
      frameRef.current = undefined;
    }
  }, []);

  const beginTransition = React.useCallback(() => {
    endTransition();
    if (reducedMotion) return;

    transitioningRef.current = true;
    // Wait for the primitive to mount the content or update data-state before
    // reading the animation generated by the utility classes.
    frameRef.current = requestFrame(() => {
      frameRef.current = requestFrame(() => {
        frameRef.current = undefined;
        const content = contentRef.current;
        if (!content) {
          endTransition();
          return;
        }
        const totalMs = getAnimationTotalMs(content);
        if (totalMs <= 0) {
          endTransition();
          return;
        }
        // animationend is authoritative; this only prevents a permanent lock
        // if the element is removed or the browser drops the event.
        fallbackTimerRef.current = window.setTimeout(
          endTransition,
          totalMs + ANIMATION_FALLBACK_BUFFER_MS,
        );
      });
    });
  }, [endTransition, reducedMotion]);

  React.useEffect(() => endTransition, [endTransition]);
  React.useEffect(() => {
    if (reducedMotion) endTransition();
  }, [endTransition, reducedMotion]);

  return React.useMemo(
    () => ({
      contentRef,
      reducedMotion,
      isTransitioning: () => transitioningRef.current,
      beginTransition,
      endTransition,
    }),
    [beginTransition, endTransition, reducedMotion],
  );
}

export function useOverlayAnimationRef<T extends HTMLElement>(
  guard: OverlayAnimationGuard | undefined,
  forwardedRef: React.ForwardedRef<T>,
): React.RefCallback<T> {
  const contentNodeRef = React.useRef<T | null>(null);
  const finishCanceledAnimation = React.useCallback(
    (event: Event) => {
      if (event.target === event.currentTarget) guard?.endTransition();
    },
    [guard],
  );

  return React.useCallback(
    (node: T | null) => {
      contentNodeRef.current?.removeEventListener(
        "animationcancel",
        finishCanceledAnimation,
      );
      contentNodeRef.current = node;
      node?.addEventListener("animationcancel", finishCanceledAnimation);
      if (guard) guard.contentRef.current = node;
      if (typeof forwardedRef === "function") forwardedRef(node);
      else if (forwardedRef) forwardedRef.current = node;
    },
    [finishCanceledAnimation, forwardedRef, guard],
  );
}

export function finishOverlayAnimation(
  guard: OverlayAnimationGuard | undefined,
  event: React.AnimationEvent<HTMLElement>,
): void {
  if (event.target === event.currentTarget) guard?.endTransition();
}
