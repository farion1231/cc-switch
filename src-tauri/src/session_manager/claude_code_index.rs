//! Synchronisation for Claude Desktop's Code session index.
//!
//! Claude Code transcripts remain canonical under `~/.claude/projects`. Claude
//! Desktop keeps a separate, small index for its Code entry point; importing a
//! transcript therefore only requires creating a missing index record.

use std::collections::HashSet;
use std::fs;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

use super::SessionMeta;

#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct SyncOutcome {
    pub created: usize,
    pub existing: usize,
    pub skipped: usize,
}

/// Discover existing Claude Desktop Code index directories.
///
/// The two UUID components are generated by Claude Desktop and must not be
/// hard-coded. We only write below directories that Desktop has already
/// created, preserving its account/profile layout.
pub fn index_dirs() -> Vec<PathBuf> {
    #[cfg(target_os = "macos")]
    {
        let home = crate::config::get_home_dir();
        let mut dirs = Vec::new();
        for app_name in active_app_names(&home) {
            let root = home
                .join("Library")
                .join("Application Support")
                .join(app_name)
                .join("claude-code-sessions");
            collect_index_dirs(&root, &mut dirs);
        }
        dirs.sort();
        dirs.dedup();
        dirs
    }

    #[cfg(not(target_os = "macos"))]
    {
        Vec::new()
    }
}

#[cfg(target_os = "macos")]
fn active_app_names(home: &Path) -> &'static [&'static str] {
    let config = home
        .join("Library")
        .join("Application Support")
        .join("Claude-3p")
        .join("config.json");
    if fs::read_to_string(config)
        .ok()
        .and_then(|contents| serde_json::from_str::<Value>(&contents).ok())
        .and_then(|value| {
            value
                .get("deploymentMode")
                .and_then(Value::as_str)
                .map(str::to_owned)
        })
        .as_deref()
        == Some("3p")
    {
        &["Claude-3p"]
    } else {
        &["Claude"]
    }
}

pub fn sync(sessions: &[SessionMeta]) -> Result<SyncOutcome, String> {
    sync_in_dirs(sessions, &index_dirs())
}

fn sync_in_dirs(sessions: &[SessionMeta], dirs: &[PathBuf]) -> Result<SyncOutcome, String> {
    let mut outcome = SyncOutcome::default();
    for dir in dirs {
        if !dir.is_dir() {
            continue;
        }

        let indexed = read_indexed_cli_ids(dir);
        let mut seen = indexed.clone();
        for session in sessions {
            if session.provider_id != "claude" || !is_safe_session_id(&session.session_id) {
                outcome.skipped += 1;
                continue;
            }
            if seen.contains(&session.session_id) {
                outcome.existing += 1;
                continue;
            }

            let local_id = format!("local_{}", session.session_id);
            let path = dir.join(format!("{local_id}.json"));
            // Never replace an existing file, including malformed files that
            // may have been written by a newer Desktop version.
            if path.exists() {
                outcome.existing += 1;
                seen.insert(session.session_id.clone());
                continue;
            }

            let now = unix_now_ms();
            let created_at = session.created_at.unwrap_or(now);
            let last_activity_at = session.last_active_at.unwrap_or(created_at);
            let mut record = Map::new();
            record.insert("sessionId".into(), Value::String(local_id));
            record.insert(
                "cliSessionId".into(),
                Value::String(session.session_id.clone()),
            );
            if let Some(cwd) = session.project_dir.as_deref() {
                record.insert("cwd".into(), Value::String(cwd.to_string()));
                record.insert("originCwd".into(), Value::String(cwd.to_string()));
            }
            record.insert("createdAt".into(), Value::from(created_at));
            record.insert("lastActivityAt".into(), Value::from(last_activity_at));
            record.insert("model".into(), Value::String("claude-opus-4-8".into()));
            record.insert("effort".into(), Value::String("high".into()));
            record.insert("isArchived".into(), Value::Bool(false));
            if let Some(title) = session.title.as_deref() {
                record.insert("title".into(), Value::String(title.to_string()));
                record.insert(
                    "titleSource".into(),
                    Value::String("cc-switch-import".into()),
                );
            }
            record.insert(
                "permissionMode".into(),
                Value::String("bypassPermissions".into()),
            );
            record.insert("remoteMcpServersConfig".into(), Value::Array(Vec::new()));
            record.insert(
                "chromePermissionMode".into(),
                Value::String("skip_all_permission_checks".into()),
            );
            record.insert("completedTurns".into(), Value::from(0));

            let bytes = serde_json::to_vec_pretty(&Value::Object(record))
                .map_err(|e| format!("Failed to serialize Claude Code index: {e}"))?;
            crate::config::atomic_write(&path, &bytes).map_err(|e| {
                format!("Failed to write Claude Code index {}: {e}", path.display())
            })?;
            seen.insert(session.session_id.clone());
            outcome.created += 1;
        }
    }
    Ok(outcome)
}

fn collect_index_dirs(root: &Path, dirs: &mut Vec<PathBuf>) {
    let Ok(deployment_entries) = fs::read_dir(root) else {
        return;
    };
    for deployment in deployment_entries.flatten() {
        let deployment_path = deployment.path();
        if !deployment_path.is_dir() {
            continue;
        }
        let Ok(profile_entries) = fs::read_dir(&deployment_path) else {
            continue;
        };
        for profile in profile_entries.flatten() {
            let profile_path = profile.path();
            if profile_path.is_dir() {
                dirs.push(profile_path);
            }
        }
    }
}

fn read_indexed_cli_ids(dir: &Path) -> HashSet<String> {
    let mut ids = HashSet::new();
    let Ok(entries) = fs::read_dir(dir) else {
        return ids;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().and_then(|v| v.to_str()) != Some("json") {
            continue;
        }
        let Ok(contents) = fs::read_to_string(path) else {
            continue;
        };
        let Ok(value) = serde_json::from_str::<Value>(&contents) else {
            continue;
        };
        if let Some(id) = value.get("cliSessionId").and_then(Value::as_str) {
            ids.insert(id.to_string());
        }
    }
    ids
}

fn is_safe_session_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 128
        && id
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || b"-_".contains(&byte))
}

fn unix_now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|duration| duration.as_millis().min(i64::MAX as u128) as i64)
        .unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    fn session(id: &str) -> SessionMeta {
        SessionMeta {
            provider_id: "claude".into(),
            session_id: id.into(),
            title: Some("Imported title".into()),
            summary: None,
            project_dir: Some("/tmp/project".into()),
            created_at: Some(100),
            last_active_at: Some(200),
            source_path: Some("/tmp/session.jsonl".into()),
            resume_command: None,
            account_label: Some("a@example.com".into()),
        }
    }

    #[test]
    fn creates_missing_index_without_tokens() {
        let dir = tempdir().unwrap();
        let result = sync_in_dirs(&[session("abc-123")], &[dir.path().to_path_buf()]).unwrap();
        assert_eq!(result.created, 1);
        let value: Value =
            serde_json::from_slice(&fs::read(dir.path().join("local_abc-123.json")).unwrap())
                .unwrap();
        assert_eq!(value["cliSessionId"], "abc-123");
        assert!(value.get("token").is_none());
        assert!(value.get("oauth").is_none());
    }

    #[test]
    fn existing_cli_id_is_not_duplicated_or_overwritten() {
        let dir = tempdir().unwrap();
        let path = dir.path().join("existing.json");
        fs::write(
            &path,
            r#"{"cliSessionId":"abc-123","title":"Desktop title"}"#,
        )
        .unwrap();
        let result = sync_in_dirs(&[session("abc-123")], &[dir.path().to_path_buf()]).unwrap();
        assert_eq!(result.created, 0);
        assert_eq!(result.existing, 1);
        assert_eq!(
            fs::read_to_string(path).unwrap(),
            r#"{"cliSessionId":"abc-123","title":"Desktop title"}"#
        );
    }
}
